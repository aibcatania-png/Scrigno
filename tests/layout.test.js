// Prova la disposizione in stile Enpass: barra laterale a gruppi, tag, ordinamento, scorciatoie.
const { chromium } = require(process.env.PW || 'playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', 'web');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.webmanifest': 'application/manifest+json' };
const srv = http.createServer((q, s) => {
  const p = path.join(root, decodeURIComponent(new URL(q.url, 'http://x').pathname).replace(/\/$/, '/index.html'));
  fs.readFile(p, (e, d) => { if (e) { s.writeHead(404); s.end(); } else { s.writeHead(200, { 'Content-Type': types[path.extname(p)] || 'application/octet-stream' }); s.end(d); } });
}).listen(0);
let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log('FAIL', m); } else console.log('ok  ', m); };
const PW = 'una-frase-molto-lunga-42';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  await page.goto(`http://127.0.0.1:${srv.address().port}/`);
  await page.fill('input[name=pw]', PW); await page.fill('input[name=pw2]', PW);
  await page.check('input[name=ack]'); await page.click('button[type=submit]');
  await page.waitForSelector('.shell', { timeout: 20000 });
  ok(await page.isVisible('.nav-h:has-text("Categorie")') && await page.isVisible('.nav-h:has-text("Strumenti")') && await page.isVisible('.vaultname'), 'barra laterale a gruppi con vault');

  const add = async (title, user, pw, tags) => {
    await page.keyboard.press('Control+n');
    await page.click('[data-act=newtype][data-k=login]');
    await page.fill('input[name=title]', title);
    await page.fill('input[name=f_username]', user);
    await page.fill('input[name=f_password]', pw);
    await page.fill('input[name=tags]', tags);
    await page.keyboard.press('Control+s');
    await page.waitForSelector(`.detail h2:has-text("${title}")`);
  };
  await add('Banca', 'mario', 'Banca-Sicura-2026!', 'finanza, casa');
  await add('Amazon', 'mario@ex.it', '123456', 'acquisti');
  await add('Zalando', 'mario@ex.it', 'Zal-Sicura-2026!x', 'acquisti');
  ok(await page.isVisible('.nav-h:has-text("Tag")') && await page.isVisible('.nav-btn:has-text("acquisti") .cnt:has-text("2")'), 'tag nella barra laterale con conteggi');
  ok(await page.isVisible('.nav-btn[data-k=audit] .cnt.warn'), 'Sicurezza segnala i problemi');
  await page.click('.nav-btn:has-text("acquisti")');
  ok((await page.$$('.row')).length === 2 && (await page.textContent('.list-sub')).includes('acquisti'), 'filtro per tag');
  await page.click('[data-act=section][data-k=all]');
  await page.selectOption('#sortSel', 'za');
  ok((await page.textContent('.row >> nth=0')).includes('Zalando'), 'ordinamento Z–A');
  await page.selectOption('#sortSel', 'az');
  // scorciatoie: ricerca, frecce, modifica, preferiti, copia
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+f');
  ok(await page.evaluate(() => document.activeElement.id === 'q'), 'Ctrl+F porta alla ricerca');
  await page.keyboard.press('ArrowDown');
  ok((await page.textContent('.detail h2')).includes('Amazon'), 'freccia giù apre il primo elemento');
  await page.keyboard.press('ArrowDown');
  ok((await page.textContent('.detail h2')).includes('Banca'), 'freccia giù passa al successivo');
  await page.click('.detail .dtitle');
  await page.keyboard.press('Control+Shift+C');
  ok(await page.evaluate(() => navigator.clipboard.readText()) === 'Banca-Sicura-2026!', 'Ctrl+Maiusc+C copia la password');
  await page.keyboard.press('Control+d');
  await page.waitForSelector('.star');
  ok(true, 'Ctrl+D aggiunge ai preferiti');
  await page.keyboard.press('Control+e');
  await page.waitForSelector('#editForm');
  await page.keyboard.press('Escape');
  ok(await page.isVisible('[data-act=edit]'), 'Esc annulla la modifica');
  await page.keyboard.press('?');
  ok(await page.isVisible('#scDlg'), '? mostra le scorciatoie');
  await page.keyboard.press('Escape');
  await page.click('.tag:has-text("finanza")');
  ok((await page.textContent('.list-sub')).includes('finanza'), 'clic su un tag della scheda filtra l\'elenco');
  await page.screenshot({ path: path.join(__dirname, 'shot-layout.png') });
  await page.setViewportSize({ width: 400, height: 860 });
  await page.click('[data-act=section][data-k=all]');
  const vw = await page.evaluate(() => [document.documentElement.scrollWidth, innerWidth]);
  ok(vw[0] <= vw[1], 'telefono: nessuno scorrimento orizzontale');
  await page.screenshot({ path: path.join(__dirname, 'shot-layout-mobile.png') });
  await page.keyboard.press('Control+l');
  ok(await page.isVisible('#unlockForm'), 'Ctrl+L blocca');
  ok(errors.length === 0, 'nessun errore JS ' + errors.join(' | '));
  await browser.close(); srv.close();
  console.log(fails ? `\n${fails} FALLITI` : '\nTUTTI OK');
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
